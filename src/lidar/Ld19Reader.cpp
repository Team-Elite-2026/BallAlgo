Ld19Reader::Ld19Reader(const std::string& port, int baud, double timeoutSec) {
  fd_ = open(port.c_str(), O_RDWR | O_NOCTTY | O_NONBLOCK);
  if (fd_ < 0) {
    std::cerr << "[LIDAR] open failed " << port << "\n";
    return;
  }
  termios tty{};
  tcgetattr(fd_, &tty);
  const speed_t spd = baudToSpeed(baud);
  cfsetospeed(&tty, spd);
  cfsetispeed(&tty, spd);
  tty.c_cflag = (tty.c_cflag & ~CSIZE) | CS8;
  tty.c_cflag |= CLOCAL | CREAD;
  tty.c_lflag = 0;
  tty.c_oflag = 0;
  tty.c_iflag = 0;
  tty.c_cc[VMIN] = 0;
  tty.c_cc[VTIME] = static_cast<cc_t>(timeoutSec * 10);
  tcsetattr(fd_, TCSANOW, &tty);
  std::cout << "[LIDAR] " << port << " @ " << baud << "\n";
}

Ld19Reader::~Ld19Reader() { close(); }

void Ld19Reader::close() {
  if (fd_ >= 0) {
    ::close(fd_);
    fd_ = -1;
  }
}

uint8_t Ld19Reader::crc8(const uint8_t* data, size_t len) {
  uint8_t crc = 0;
  for (size_t i = 0; i < len; ++i) crc = kCrcTable[(crc ^ data[i]) & 0xFF];
  return crc;
}

int Ld19Reader::angleStep(uint16_t start, uint16_t end, int lenMinusOne) {
  if (start <= end) return (end - start) / lenMinusOne;
  return (36000 + end - start) / lenMinusOne;
}

std::vector<LidarPoint> Ld19Reader::parseFrame(const uint8_t* frame, size_t len) const {
  std::vector<LidarPoint> pts;
  if (len != 47 || frame[0] != 0x54 || frame[1] != 0x2C) return pts;
  if (crc8(frame, len - 1) != frame[len - 1]) return pts;
  uint16_t start = frame[4] | (frame[5] << 8);
  uint16_t end = frame[42] | (frame[43] << 8);
  int step = angleStep(start, end, 11);
  for (int i = 0; i < 12; ++i) {
    int idx = 6 + i * 3;
    uint16_t dist = frame[idx] | (frame[idx + 1] << 8);
    LidarPoint p;
    p.distanceMm = dist;
    p.intensity = frame[idx + 2];
    p.angleCd = static_cast<uint16_t>((start + step * i) % 36000);
    pts.push_back(p);
  }
  return pts;
}

std::vector<LidarPoint> Ld19Reader::pollPoints() {
  std::vector<LidarPoint> out;
  if (fd_ < 0) return out;
  uint8_t buf[512];
  ssize_t n = read(fd_, buf, sizeof(buf));
  if (n > 0) buffer_.insert(buffer_.end(), buf, buf + n);
  constexpr size_t kFrameLen = 47;
  while (buffer_.size() >= kFrameLen) {
    auto it = std::find(buffer_.begin(), buffer_.end(), 0x54);
    if (it == buffer_.end()) {
      buffer_.clear();
      break;
    }
    size_t start = it - buffer_.begin();
    if (start > 0) buffer_.erase(buffer_.begin(), buffer_.begin() + start);
    if (buffer_.size() < kFrameLen) break;
    if (buffer_[1] != 0x2C) {
      buffer_.erase(buffer_.begin());
      continue;
    }
    auto framePts = parseFrame(buffer_.data(), kFrameLen);
    buffer_.erase(buffer_.begin(), buffer_.begin() + kFrameLen);
    out.insert(out.end(), framePts.begin(), framePts.end());
  }
  return out;
}

